"""Univariate expansions: Daniels (density) and Hauschildt-Robinson (distribution function),
and the Rice expansion of a ratio density."""
from __future__ import annotations

import math

import numpy as np

from .util import SQRT2PI, acoef, dcoef, fact, gauher, hcoef, normcdf, normpdf


def spa_uni(Kd, shat, xbar, order, uthr=2.5):
    """Saddlepoint approximations of orders ``1..order`` of the density and the distribution
    function of a scalar variable at ``xbar`` from the derivatives of its cumulant generating
    function at the saddlepoint: ``Kd[k] = K^(k)(shat)``, ``k = 0..2*order+1``.

    Returns a dict with ``pdf`` (Daniels expansion with the terms ``m <= M-1``), ``cdf``
    (Hauschildt-Robinson expansion of ``P(X <= xbar)`` with the terms ``m <= 2M-1``), ``upp``
    (the same expansion of ``P(X > xbar)``, computed directly) and ``kappa`` (cancellation
    indicator), each an array over the orders. Both signs of ``shat`` are handled. The integrals
    ``I_m(u)``, ``u = shat K''^(1/2)``, are generated by the forward recursion for ``|u| <= uthr``
    and by 80-point Gauss-Hermite quadrature otherwise."""
    if order < 1:
        raise ValueError("spa_uni: order must be a positive integer")
    Kd = np.asarray(Kd, dtype=float)
    shat = float(shat)
    xbar = float(xbar)
    p = 2 * order - 1
    N = p + 2
    if len(Kd) < N + 1:
        raise ValueError(f"spa_uni: need K^(k) for k = 0..{N}")
    K2 = Kd[2]
    sK2 = math.sqrt(K2)
    theta = np.array([Kd[k] / (fact(k) * sK2 ** k) for k in range(3, N + 1)])   # theta[k-3] = theta_k
    J = N - 2
    d = dcoef(theta, J)
    h = hcoef(2 * J)
    f0 = math.exp(Kd[0] - shat * xbar) / math.sqrt(2 * math.pi * K2)
    pdf = np.zeros(order)
    s = 1.0
    for M in range(1, order + 1):
        if M > 1:
            s += acoef(d, h, M - 1, 2 * (M - 1))
        pdf[M - 1] = f0 * s
    u = shat * sK2
    Ephi = math.exp(Kd[0] - shat * xbar) / SQRT2PI
    nI = 3 * p + 1
    if abs(u) <= uthr:
        R = np.zeros(nI)
        R[0] = normcdf(-u) / normpdf(u) if shat >= 0 else -normcdf(u) / normpdf(u)
        for i in range(0, 3 * p):
            R[i + 1] = (h[i // 2] - u * R[i]) if i % 2 == 0 else -u * R[i]
    else:
        R = _Iherm(abs(u), nI - 1)
        if shat < 0:
            for m in range(nI):
                R[m] = -((-1) ** m) * R[m]
    cdf = np.zeros(order)
    upp = np.zeros(order)
    kappa = np.zeros(order)
    s = R[0]
    sa = abs(R[0])
    m = 0
    for M in range(1, order + 1):
        while m < 2 * M - 1:
            m += 1
            for r in range(1, m + 1):
                term = d[r, m] * R[m + 2 * r]
                s += term
                sa += abs(term)
        if shat >= 0:
            upp[M - 1] = Ephi * s
            cdf[M - 1] = 1 - upp[M - 1]
        else:
            cdf[M - 1] = -Ephi * s
            upp[M - 1] = 1 - cdf[M - 1]
        kappa[M - 1] = sa / abs(s)
    return dict(pdf=pdf, cdf=cdf, upp=upp, kappa=kappa)


def _Iherm(u, mmax):
    """R[m] = I_m(u)/phi(u), m = 0..mmax, u > 0, by 80-point Gauss-Hermite quadrature."""
    xg, wg = gauher(80)
    q = wg / (u ** 2 + xg ** 2)
    x2 = xg ** 2
    J = mmax // 2 + 1
    Mj = np.zeros(J + 1)
    for j in range(J + 1):
        Mj[j] = q.sum()
        q = q * x2
    R = np.zeros(mmax + 1)
    for m in range(mmax + 1):
        k = m // 2
        R[m] = (-1) ** k * u * Mj[k] if m % 2 == 0 else (-1) ** k * Mj[k + 1]
    return R


def spa_ratio_pdf(KWd, gd, shat, order):
    """Rice (Laplace) expansion of orders ``1..order`` of ``(2 pi i)^-1 int exp{K_W(s)} g(s) ds``
    through the saddlepoint ``shat`` of ``K_W`` (``K_W'(shat) = 0``): ``KWd[k] = K_W^(k)(shat)``,
    ``k = 0..2*order``, and ``gd[l] = g^(l)(shat)``, ``l = 0..2*order-2``. For the density of
    ``R = X/Y`` at ``r`` with ``Y > 0`` and joint cumulant generating function ``K(s, t)``, take
    ``K_W(s) = K(s, -r s)`` and ``g(s) = dK/dt`` at ``t = -r s``."""
    if order < 1:
        raise ValueError("spa_ratio_pdf: order must be a positive integer")
    KWd = np.asarray(KWd, dtype=float)
    gd = np.asarray(gd, dtype=float)
    if len(KWd) < 2 * order + 1:
        raise ValueError(f"spa_ratio_pdf: need K_W^(k)(shat) for k = 0..{2*order}")
    if len(gd) < 2 * order - 1:
        raise ValueError(f"spa_ratio_pdf: need g^(l)(shat) for l = 0..{2*order-2}")
    N = 2 * order
    K2 = KWd[2]
    sK2 = math.sqrt(K2)
    theta = np.array([KWd[k] / (fact(k) * sK2 ** k) if k < len(KWd) else 0.0 for k in range(3, N + 3)])
    J = N
    d = dcoef(theta, J)
    h = hcoef(2 * J)
    g0 = gd[0]
    gam = np.zeros(N + 1)
    for l in range(0, N - 1):
        gam[l] = gd[l] / (fact(l) * g0 * sK2 ** l)
    lead = math.exp(KWd[0]) * g0 / math.sqrt(2 * math.pi * K2)
    pdf = np.zeros(order)
    s = 0.0
    for M in range(1, order + 1):
        j = M - 1
        for kk in range(0, 2 * j + 1):
            s += gam[2 * j - kk] * acoef(d, h, j, kk)
        pdf[M - 1] = lead * s
    return pdf
