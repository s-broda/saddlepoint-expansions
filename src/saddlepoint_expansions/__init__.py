"""Saddlepoint expansions of any order for tail probabilities and densities of random vectors,
from the cumulant generating function alone (Broda and Kan, "Uniform saddlepoint expansions for
multivariate tail probabilities").

The user supplies the cumulant generating function as an ordinary Python function wrapped in a
:class:`CGF`; every derivative the expansions need is generated by Taylor-mode automatic
differentiation (:mod:`saddlepoint_expansions.taylor`), directly in the whitened coordinates in
which the terms are evaluated. The main functions are :func:`tailprob`, :func:`density`,
:func:`ratio_density`, :func:`ratio_tailprob`, :func:`saddlepoint` and :func:`derivatives`, and, for a
Studentized mean ``X/sqrt(Y)`` (Bao, Broda and Kan, "Inversion formulas and saddlepoint expansions
for Studentized means"), :func:`studentized_density`, :func:`studentized_tailprob` and
:func:`studentized_quantile`.
"""
